const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'dockcheck-world.html'),'utf8');
const standalone=html.replace(/<script src="([^"]+)"><\/script>/g,(_,name)=>{
  const source=fs.readFileSync(path.join(root,name),'utf8').replace(/<\/script/gi,'<\\/script');
  return `<script>\n/* Bundled from ${name} */\n${source}\n</script>`;
});
fs.writeFileSync(path.join(root,'dockcheck-demo.html'),'<!-- Generated by node scripts/build-demo.cjs; edit source files instead. -->\n'+standalone);
console.log('Built dockcheck-demo.html: all scripts embedded, no external dependencies.');
